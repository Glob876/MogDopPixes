import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
const result = spawnSync(
  "wasm-pack",
  [
    "build",
    "crates/pixel-core",
    "--release",
    "--target",
    "web",
    "--out-dir",
    "../../src/wasm",
  ],
  { stdio: "inherit", env: { ...process.env, CARGO_BUILD_JOBS: "1" } },
);
if (result.status !== 0) process.exit(result.status || 1);
const binary = readFileSync("src/wasm/mogdoppixes_core_bg.wasm").toString(
  "base64",
);
writeFileSync(
  "src/wasm-binary.ts",
  `// Generated by scripts/build-core.mjs.\nexport const coreBinary = '${binary}';\n`,
);
